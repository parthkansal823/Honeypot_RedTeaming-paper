#!/usr/bin/env python3
"""
validate_logs.py
-----------------
Scans a directory of ai_attacker.py session JSON logs for signs of the
marker-leak / cross-turn output corruption bug: a slow honeypot response
(observed on the "dynamic"/LLM-backed honeypot condition) can cause
HoneypotSession._drain()'s idle-timeout to fire before the real output and
completion marker have fully arrived. The stale bytes then show up prepended
to the NEXT turn's captured output instead of the current one, corrupting
both turns - and, more importantly, every attacker LLM call made afterward,
since the corrupted text gets fed back in as "Command output:\\n{output}".

USAGE
    python validate_logs.py logs/dynamic/

A turn is flagged as suspect if its `output` contains:
  - a leftover completion marker string ("__CMDDONE_...") - this should
    never survive send_command()'s own strip regexes for the CURRENT
    turn's marker, so any occurrence means a DIFFERENT turn's marker leaked
    through into this one
  - more than one shell-prompt-like line - a clean single-command capture
    should only ever end with one prompt, not have one embedded mid-output
    followed by more content

Any session containing at least one suspect turn is reported as
NEEDS_RERUN: once one turn is corrupted, every later turn in that session
was generated by the attacker LLM reacting to garbled context, so patching
just the flagged turn's text after the fact doesn't recover a clean session.
"""
import json
import re
import sys
from pathlib import Path

MARKER_LEAK_RE = re.compile(r"__CMDDONE_[0-9a-f]{8}__")
PROMPT_LINE_RE = re.compile(r"(?m)^[^\s@]+@[^\s:]+:\S*[#$]\s*$")


def check_turn(turn: dict) -> list[str]:
    reasons = []
    output = turn.get("output")
    if not output:
        return reasons
    if MARKER_LEAK_RE.search(output):
        reasons.append("leftover completion marker found in output (another turn's marker leaked in)")
    prompt_hits = PROMPT_LINE_RE.findall(output)
    if len(prompt_hits) > 1:
        reasons.append(f"{len(prompt_hits)} shell prompts found in one turn's output (expected at most 1)")
    return reasons


def check_session(path: Path) -> dict:
    data = json.loads(path.read_text())
    suspect_turns = []
    for turn in data.get("turns", []):
        reasons = check_turn(turn)
        if reasons:
            suspect_turns.append({"turn": turn.get("turn"), "command": turn.get("command"), "reasons": reasons})
    return {
        "session_id": data.get("session_id"),
        "status": data.get("status"),
        "total_turns": data.get("total_turns"),
        "suspect_turns": suspect_turns,
    }


def main() -> None:
    if len(sys.argv) != 2:
        print("usage: python validate_logs.py <logs_dir>", file=sys.stderr)
        sys.exit(1)

    logs_dir = Path(sys.argv[1])
    files = sorted(logs_dir.glob("*.json"))
    if not files:
        print(f"no .json files found in {logs_dir}", file=sys.stderr)
        sys.exit(1)

    total = 0
    flagged_sessions = []

    for f in files:
        try:
            result = check_session(f)
        except Exception as e:  # noqa: BLE001
            print(f"  ! could not parse {f.name}: {e!r}", file=sys.stderr)
            continue
        total += 1
        if result["suspect_turns"]:
            flagged_sessions.append((f.name, result))

    print(f"\nChecked {total} session log(s) in {logs_dir}")
    print(f"{len(flagged_sessions)} session(s) contain at least one suspect (likely corrupted) turn\n")

    if flagged_sessions:
        print("NEEDS_RERUN (corrupted context propagates to every later turn in the session):")
        for fname, result in flagged_sessions:
            print(f"  {fname}  [{result['session_id']}, status={result['status']}]")
            for st in result["suspect_turns"]:
                print(f"      turn {st['turn']} ({st['command']!r}): {', '.join(st['reasons'])}")
        print()

    clean = total - len(flagged_sessions)
    pct = (100 * clean / total) if total else 0.0
    print(f"Summary: {clean}/{total} sessions clean ({pct:.1f}%)")


if __name__ == "__main__":
    main()